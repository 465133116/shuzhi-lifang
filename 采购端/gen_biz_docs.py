BL = RGBColor(0x1F, 0x38, 0x64); BA = RGBColor(0x25, 0x63, 0xEB); BK = RGBColor(0x33, 0x33, 0x33)
GR = RGBColor(0x64, 0x74, 0x8B); GN = RGBColor(0x10, 0xB9, 0x81); RD = RGBColor(0xB9, 0x1C, 0x1C)

def rf(run, cn, sz, b=False, c=None):
    run.font.size = Pt(sz); run.font.bold = b; run.font.name = cn
    rP = run._element.get_or_add_rPr()
    rP.append(parse_xml(f'<w:rFonts {nsdecls("w")} w:eastAsia="{cn}"/>'))
    if c: run.font.color.rgb = c

def T(text, lv=0):
    p = doc.add_paragraph(); r = p.add_run(text)
    sizes = {0: (20, True, BL), 1: (15, True, BL), 2: (12.5, True, BA), 3: (11, True, BK)}
    sz, b, c = sizes.get(lv, (11, False, BK)); rf(r, '黑体', sz, b, c)
    if lv == 0: p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    elif lv == 1: p.paragraph_format.space_before = Pt(18); p.paragraph_format.space_after = Pt(6)
    elif lv == 2: p.paragraph_format.space_before = Pt(12); p.paragraph_format.space_after = Pt(4)
    else: p.paragraph_format.space_before = Pt(8)

def B(text, c=None, b=False):
    p = doc.add_paragraph(); r = p.add_run(text); rf(r, '宋体', 11, b, c or BK)
    p.paragraph_format.space_after = Pt(2)
    return p

def TB(rows, widths=None):
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    t.style = 'Table Grid'
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            cell = t.cell(i, j); cell.text = ''
            p = cell.paragraphs[0]; r = p.add_run(str(val))
            rf(r, '宋体', 10, i == 0, RGBColor(0xFF, 0xFF, 0xFF) if i == 0 else (BK if j == 0 else GR))
            if i == 0:
                sh = parse_xml(f'<w:shd {nsdecls("w")} w:fill="1F3864"/>')
                cell._tc.get_or_add_tcPr().append(sh)
            elif i % 2 == 0:
                sh = parse_xml(f'<w:shd {nsdecls("w")} w:fill="F2F4F8"/>')
                cell._tc.get_or_add_tcPr().append(sh)
    doc.add_paragraph()
    return t

