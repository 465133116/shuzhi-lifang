_USED = set()

# 引号类字符统一映射为同一占位符，消除「」vs“”vs" 的引号样式噪音（1:1映射，索引不变）
_QT = str.maketrans('「」\u201c\u201d"\'', '\u25ae\u25ae\u25ae\u25ae\u25ae\u25ae')

def norm(s):
    return s.translate(_QT)

def find_match(new_text):
    best_i, best_r = -1, 0.0
    nn = norm(new_text)
    for i, old in enumerate(BLOCKS):
        if i in _USED:
            continue
        r = difflib.SequenceMatcher(None, norm(old), nn).ratio()
        if r > best_r:
            best_i, best_r = i, r
    if best_i >= 0 and best_r >= 0.35:
        _USED.add(best_i)
        return BLOCKS[best_i]
    return None

