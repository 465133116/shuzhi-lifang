def set_font(run, name='宋体', size=11, bold=False, color=None):
    run.font.name = name
    run._element.rPr.rFonts.set(qn('w:eastAsia'), name)
    run.font.size = Pt(size)
    run.font.bold = bold
    if color:
        run.font.color.rgb = RGBColor(*color)

def render_diff(p, new_text, old_text, name='宋体', size=11, bold=False, black_color=None):
    """按原文对齐渲染：equal=黑色（black_color），insert/replace=红色。"""
    if PLAIN_MODE:
        set_font(p.add_run(new_text), name, size, bold, black_color)
        return
    if old_text is None:
        set_font(p.add_run(new_text), name, size, bold, RED)
        return
    sm = difflib.SequenceMatcher(None, norm(old_text), norm(new_text))
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        seg = new_text[j1:j2]
        if not seg:
            continue
        red = tag in ('insert', 'replace')
        set_font(p.add_run(seg), name, size, bold, RED if red else black_color)

