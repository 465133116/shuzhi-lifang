def add_item(label, desc):
    p = doc.add_paragraph()
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.left_indent = Cm(0.74)
    p.paragraph_format.space_after = Pt(2)
    set_font(p.add_run('▪ '), '宋体', 11, False)
    if PLAIN_MODE:
        set_font(p.add_run(label + '：'), '宋体', 11, True)
        set_font(p.add_run(desc), '宋体', 11)
        return
    old = find_match(label + '：' + desc)
    if old is None:
        set_font(p.add_run(label + '：' + desc), '宋体', 11, True, RED)
        return
    if '：' in old:
        old_label, old_desc = old.split('：', 1)
    else:
        old_label, old_desc = old, ''
    render_diff(p, label, old_label, '宋体', 11, True)
    set_font(p.add_run('：'), '宋体', 11, False)
    render_diff(p, desc, old_desc, '宋体', 11, False)

def shade_cell(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:fill'), hexcolor)
    tcPr.append(shd)

def set_cell_layout(cell, width, center=False):
    """固定列宽 + 垂直居中 + 单元格内边距"""
    cell.width = width
    tcPr = cell._tc.get_or_add_tcPr()
    vAlign = OxmlElement('w:vAlign')
    vAlign.set(qn('w:val'), 'center')
    tcPr.append(vAlign)
    tcMar = OxmlElement('w:tcMar')
    for side, val in [('top', 90), ('bottom', 90), ('left', 110), ('right', 110)]:
        el = OxmlElement('w:' + side)
        el.set(qn('w:w'), str(val))
        el.set(qn('w:type'), 'dxa')
        tcMar.append(el)
    tcPr.append(tcMar)
    if center:
        for p in cell.paragraphs:
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER

def set_row_height(row, twips=420):
    trPr = row._tr.get_or_add_trPr()
    trHeight = OxmlElement('w:trHeight')
    trHeight.set(qn('w:val'), str(twips))
    trHeight.set(qn('w:hRule'), 'atLeast')
    trPr.append(trHeight)

def add_table(headers, rows):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    # 固定布局，列宽不随内容伸缩
    tblPr = t._tbl.tblPr
    layout = OxmlElement('w:tblLayout')
    layout.set(qn('w:type'), 'fixed')
    tblPr.append(layout)
    widths = [Cm(2.6), Cm(5.7), Cm(5.7)]
    all_new = list(headers) + [c for row in rows for c in row]
    matched = [find_match(v) if not PLAIN_MODE else v for v in all_new]
    idx = 0
    hdr = t.rows[0].cells
    for i in range(len(headers)):
        p = hdr[i].paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        render_diff(p, headers[i], matched[idx], '宋体', 11, True, black_color=(255, 255, 255))
        shade_cell(hdr[i], '1F3864')
        set_cell_layout(hdr[i], widths[i])
        idx += 1
    set_row_height(t.rows[0], 460)
    for ri, row in enumerate(rows):
        cells = t.add_row().cells
        for ci, val in enumerate(row):
            p = cells[ci].paragraphs[0]
            render_diff(p, val, matched[idx], '宋体', 10.5, False)
            if ri % 2 == 1:
                shade_cell(cells[ci], 'F2F2F2')
            set_cell_layout(cells[ci], widths[ci], center=True)
            idx += 1
        set_row_height(t.rows[ri + 1], 460)
    doc.add_paragraph()

