BLOCKS = []
for _child in _orig.element.body.iterchildren():
    if _child.tag == qn('w:p'):
        _s = ''.join(_t.text or '' for _t in _child.findall('.//' + qn('w:t')))
        if _s.strip():
            BLOCKS.append(_s)
    elif _child.tag == qn('w:tbl'):
        for _tc in _child.findall('.//' + qn('w:tc')):
            _s = ''.join(_t.text or '' for _t in _tc.findall('.//' + qn('w:t')))
