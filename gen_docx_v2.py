def CBG(cell,hx):
    cell._tc.get_or_add_tcPr().append(parse_xml(f'<w:shd {nsdecls("w")} w:fill="{hx}"/>'))

def TB(headers,rows,ws=None):
    t=doc.add_table(rows=1+len(rows),cols=len(headers))
    t.style='Table Grid'; t.alignment=WD_TABLE_ALIGNMENT.CENTER
    for i,h in enumerate(headers):
        cl=t.rows[0].cells[i]; cl.text=''; p=cl.paragraphs[0]; r=p.add_run(h)
        rf(r,'黑体',10,True,WH); p.alignment=WD_ALIGN_PARAGRAPH.CENTER; CBG(cl,'1F3864')
    for ri,rd in enumerate(rows):
        for ci,v in enumerate(rd):
            cl=t.rows[ri+1].cells[ci]; cl.text=''; p=cl.paragraphs[0]; r=p.add_run(str(v))
            rf(r,'宋体',9.5)
            if ri%2==1: CBG(cl,'F0F4F8')
    if ws:
        for i,w in enumerate(ws):
            for row in t.rows: row.cells[i].width=Cm(w)
    doc.add_paragraph(); return t

