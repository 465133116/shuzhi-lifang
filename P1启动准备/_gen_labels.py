def style_cell(cell, font_size=11, bold=False, color=TEXT, bg=None, align='left', wrap=True):
    cell.font = Font(name='Microsoft YaHei', size=font_size, bold=bold, color=color)
    if bg:
        cell.fill = PatternFill(start_color=bg, end_color=bg, fill_type='solid')
    cell.alignment = Alignment(horizontal=align, vertical='center', wrap_text=wrap)
    cell.border = thin_border

def style_header(ws, row, ncols, cat=None):
    bg = CAT_COLORS.get(cat, None)
    for c in range(1, ncols+1):
        cell = ws.cell(row=row, column=c)
        style_cell(cell, font_size=11, bold=True, color='ffffff', bg=bg or BG_HEADER, align='center')

def auto_width(ws, min_w=10, max_w=55):
    for col in ws.columns:
        letter = get_column_letter(col[0].column)
        lengths = []
        for cell in col:
            if cell.value:
                lines = str(cell.value).split('\n')
                lengths.append(max(len(l) for l in lines))
        best = min(max(max(lengths)+2 if lengths else min_w, min_w), max_w)
        ws.column_dimensions[letter].width = best

def set_bg(ws, bg=BG_DARK):
    ws.sheet_properties.tabColor = bg[:6] if len(bg)==6 else '1e293b'

# ═══════════════════════════════════════
wb = openpyxl.Workbook()

# ── 辅助函数 ──
def make_sheet(wb, title, rows, headers, tab_color=None):
    ws = wb.create_sheet(title) if title != wb.sheetnames[0] else wb.active
    ws.title = title
    set_bg(ws, tab_color or BG_DARK)

    ncols = len(headers)
    # 写表头
    for c, h in enumerate(headers, 1):
        cell = ws.cell(row=1, column=c, value=h)
    style_header(ws, 1, ncols)

    # 写数据
    for r, row in enumerate(rows, 2):
        for c, val in enumerate(row, 1):
            cell = ws.cell(row=r, column=c, value=val)
            style_cell(cell, font_size=10, color=TEXT, bg=BG_CARD if r%2==0 else BG_DARK)
            # 特殊颜色
            if c == 1 and str(val) in CAT_COLORS:
                cell.font = Font(name='Microsoft YaHei', size=11, bold=True, color=CAT_COLORS[str(val)])

    # 冻结
    ws.freeze_panes = 'A2'
    auto_width(ws)
    return ws

