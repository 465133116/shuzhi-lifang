def add_body(doc, text, bold=False, indent=True):
    p = doc.add_paragraph()
    if indent:
        p.paragraph_format.first_line_indent = Pt(22)
    p.paragraph_format.space_after = Pt(4)
    r = p.add_run(text); r.bold = bold; r.font.size = Pt(11)
    r.font.name = FONT_BODY; r.element.rPr.rFonts.set(qn('w:eastAsia'), FONT_BODY)

def add_bullet(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Pt(22)
    p.paragraph_format.space_after = Pt(3)
    r = p.add_run(text); r.font.size = Pt(11)
    r.font.name = FONT_BODY; r.element.rPr.rFonts.set(qn('w:eastAsia'), FONT_BODY)

def add_table(doc, headers, rows, widths=None, size=9):
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = 'Table Grid'; t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    for i, h in enumerate(headers):
        scf(t.rows[0].cells[i], h, bold=True, size=Pt(size), align=WD_ALIGN_PARAGRAPH.CENTER, color=RGBColor(255, 255, 255))
        if widths: t.rows[0].cells[i].width = Cm(widths[i])
    shade_cells(t.rows[0], "1F3864")
    for ri, rd in enumerate(rows):
        for ci, v in enumerate(rd):
            scf(t.rows[ri + 1].cells[ci], str(v) if v else '', size=Pt(size))
            if widths: t.rows[ri + 1].cells[ci].width = Cm(widths[ci])
        if ri % 2 == 1:
            shade_cells(t.rows[ri + 1], "F2F2F2")
    doc.add_paragraph()

def cover(doc, title, subtitle, meta_lines):
    doc.add_paragraph(); doc.add_paragraph()
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(60); p.paragraph_format.space_after = Pt(12)
    r = p.add_run(title); r.bold = True; r.font.size = Pt(22)
    r.font.name = FONT_TITLE; r.element.rPr.rFonts.set(qn('w:eastAsia'), FONT_TITLE)
    for line in subtitle:
        p2 = doc.add_paragraph(); p2.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p2.paragraph_format.space_after = Pt(6)
        r2 = p2.add_run(line); r2.font.size = Pt(13); r2.font.color.rgb = RGBColor(100, 116, 139)
        r2.font.name = FONT_BODY; r2.element.rPr.rFonts.set(qn('w:eastAsia'), FONT_BODY)
    doc.add_paragraph()
