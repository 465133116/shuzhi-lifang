BG_DARK   = "0f172a"
BG_CARD   = "1e293b"
BG_HEADER = "1a2234"
TEXT       = "e2e8f0"
TEXT_DIM   = "94a3b8"

thin = Border(left=Side('thin','334155'),right=Side('thin','334155'),
              top=Side('thin','334155'),bottom=Side('thin','334155'))

def sc(cell, sz=10, bold=False, color=TEXT, bg=None):
    cell.font = Font(name='Microsoft YaHei', size=sz, bold=bold, color=color)
    if bg: cell.fill = PatternFill(start_color=bg, end_color=bg, fill_type='solid')
    cell.alignment = Alignment(horizontal='left', vertical='center', wrap_text=True)
    cell.border = thin

def sh(ws, row, n):
    for c in range(1, n+1):
        sc(ws.cell(row=row, column=c), sz=11, bold=True, color='ffffff', bg=BG_HEADER)

def aw(ws, mn=10, mx=60):
    for col in ws.columns:
        l = get_column_letter(col[0].column)
        lens = [max(len(ln) for ln in str(c.value or '').split('\n')) for c in col]
        ws.column_dimensions[l].width = min(max(max(lens)+2, mn), mx)

def mk(wb, title, rows, headers, tab=None):
    ws = wb.create_sheet(title)
    ws.sheet_properties.tabColor = (tab or BG_DARK)[:6]
    for c,h in enumerate(headers,1): ws.cell(row=1,column=c,value=h)
    sh(ws,1,len(headers))
    for r,row in enumerate(rows,2):
        for c,v in enumerate(row,1):
            cell = ws.cell(row=r,column=c,value=v)
            sc(cell, sz=10, color=TEXT, bg=BG_CARD if r%2==0 else BG_DARK)
    ws.freeze_panes = 'A2'; aw(ws)
    return ws

