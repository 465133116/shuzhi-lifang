def scf(cell, text='', bold=False, size=Pt(10), align=WD_ALIGN_PARAGRAPH.LEFT, color=None):
    cell.text = ''; p = cell.paragraphs[0]; p.alignment = align
    p.paragraph_format.space_before = Pt(2); p.paragraph_format.space_after = Pt(2)
