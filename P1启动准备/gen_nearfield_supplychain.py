def shade_cells(row, color="D9E2F3"):
    for c in row.cells:
        s = parse_xml(f'<w:shd {nsdecls("w")} w:fill="{color}"/>')
        c._tc.get_or_add_tcPr().append(s)

def add_table(headers, rows, col_widths=None):
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        scf(t.rows[0].cells[i], h, bold=True, size=Pt(9.5),
            align=WD_ALIGN_PARAGRAPH.CENTER, color=RGBColor(255, 255, 255))
    shade_cells(t.rows[0], "1F3864")
    for ri, rd in enumerate(rows):
        for ci, v in enumerate(rd):
            scf(t.rows[ri + 1].cells[ci], str(v) if v is not None else '', size=Pt(9))
        if ri % 2 == 1:
            shade_cells(t.rows[ri + 1], "F2F2F2")
    if col_widths:
        for row in t.rows:
            for i, w in enumerate(col_widths):
                if i < len(row.cells):
                    row.cells[i].width = Cm(w)
    doc.add_paragraph()
    return t

