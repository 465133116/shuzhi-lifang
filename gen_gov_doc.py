from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side

HDR_FILL = PatternFill('solid', fgColor='1F3864')
ALT_FILL = PatternFill('solid', fgColor='F2F5F9')
SEC_FILL = PatternFill('solid', fgColor='DDE7F3')
HDR_FONT = Font(name='微软雅黑', size=10, bold=True, color='FFFFFF')
BODY_FONT = Font(name='微软雅黑', size=10)
TITLE_FONT = Font(name='微软雅黑', size=13, bold=True, color='1F3864')
SEC_FONT = Font(name='微软雅黑', size=10.5, bold=True, color='1F3864')
THIN = Border(*[Side(style='thin', color='B8C4D9')] * 4)
WRAP = Alignment(wrap_text=True, vertical='center')
CENTER = Alignment(horizontal='center', vertical='center', wrap_text=True)

def sheet(ws, title, subtitle, headers, rows, widths):
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=len(headers))
    c = ws.cell(1, 1, title)
    c.font = TITLE_FONT
    ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=len(headers))
    c2 = ws.cell(2, 1, subtitle)
    c2.font = Font(name='微软雅黑', size=9, color='666666')
    hr = 4
    for j, h in enumerate(headers, 1):
        cc = ws.cell(hr, j, h)
        cc.font = HDR_FONT
        cc.fill = HDR_FILL
        cc.alignment = CENTER
        cc.border = THIN
    for i, row in enumerate(rows):
        for j, v in enumerate(row, 1):
            cc = ws.cell(hr + 1 + i, j, v)
            cc.font = BODY_FONT
            cc.alignment = WRAP if j != 1 or len(str(v)) > 14 else Alignment(vertical='center', wrap_text=True)
            cc.border = THIN
            if i % 2 == 1:
                cc.fill = ALT_FILL
    for j, w in enumerate(widths, 1):
        ws.column_dimensions[chr(64 + j)].width = w
    ws.row_dimensions[1].height = 26
    ws.freeze_panes = 'A5'

